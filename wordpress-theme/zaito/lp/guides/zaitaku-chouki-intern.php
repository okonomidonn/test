<h2 id="time">どのくらい働く必要がある？</h2>
<p>在宅の長期インターンは、「週2〜3日以上」「週15時間以上」のように、週の稼働を条件にしている求人が多くあります。掲載中の<?php echo (int) count( $zaito_ijobs ); ?>件のうち<?php echo (int) $zaito_period; ?>件は、「3か月以上」「半年以上」など、続けてほしい期間も書かれています。</p>
<p>在宅でも、平日の日中にチャットで連絡がとれることや、決まった時間の打ち合わせへの参加を求められることがあります。授業の時間割やテスト期間と合うかを、応募する前に確かめておきましょう。</p>

<h2 id="flow">探し方と選考の流れ</h2>
<p><b>探し方：</b>長期インターンの求人サイト、企業の採用ページ、WantedlyなどのSNS型の求人サービスで探せます。ただし「リモート可」と書かれていても、最初の研修や週1回の出社がある求人もあるため、出社の有無は必ず確認しましょう。zaitoでは、出社がないことを確かめた求人だけを<a href="<?php echo esc_url( zaito_remote_condition_url( 'gakusei' ) ); ?>">学生OKの在宅求人</a>にまとめています。</p>
<p><b>選考の流れ：</b>多くの企業は、書類（または応募フォーム）のあとに、オンラインの面談を1〜2回行います。エンジニアやデザインの求人では、課題や作品の提出を求められることもあります。面談では、週にどのくらい働けるか、いつまで続けられるか、なぜその仕事に興味を持ったかを、具体的に話せるようにしておきましょう。</p>

