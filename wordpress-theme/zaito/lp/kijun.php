<body>
<?php zaito_remote_header(); ?>
<main class="wrap doc">
  <a class="back" href="<?php echo esc_url( home_url( '/' ) ); ?>"><span class="ms" aria-hidden="true">arrow_back</span>求人一覧へ</a>
  <h1>zaitoの掲載基準</h1>
  <p class="lead">zaitoは、出社なしで働けることを運営が募集ページで確かめた求人だけを載せています。「在宅OK」と書かれていても、研修や会議で出社がある求人は載せていません。</p>

  <h2>載せる求人（すべてに当てはまるもの）</h2>
  <ul>
    <li>募集ページに「フルリモート」「完全在宅」など、在宅で働けることがはっきり書かれている</li>
    <li>入社初日・研修・定例会・合宿・お客様先への訪問などで、出社や現地への参加を求める記載がない</li>
    <li>「基本は」「原則」「リモート中心」のような、例外がありうる書き方になっていない</li>
    <li>仕事内容・報酬・稼働時間・応募できる人が分かる（報酬が書かれていない求人は、そのことを表示しています）</li>
    <li>応募する前や働き始める前に、働く人が教材費・登録料などを払う仕組みがない</li>
  </ul>

  <h2>載せない求人</h2>
  <ul>
    <li>出社が「推奨」「月1回」「最初の1か月だけ」など、少しでも求められるもの</li>
    <li>配達・訪問・撮影など、仕事そのもので外に出るもの</li>
    <li>募集ページの情報が少なく、出社がないと言い切れないもの（研修の場所が書かれていないなど）</li>
    <li>働く前に費用がかかるもの</li>
  </ul>
  <p>この基準に合わないと分かった求人は、一度載せたものでも外しています。</p>

  <h2>確認のしかた</h2>
  <ul>
    <li>運営が、企業の募集ページ（または企業が掲載している求人サイト）を読んで、上の点を確かめています。</li>
    <li>各求人のページに、運営が確認した日を表示しています。</li>
    <li>2週間に1回、募集が続いているか、条件が変わっていないかを確認し直しています。募集が終わった求人は外します。</li>
  </ul>

  <h2>住んでいる場所と契約の形</h2>
  <p>「完全在宅」と「どこに住んでいても応募できる」は別の条件です。「日本国内に住んでいる方」「海外在住は不可」などの条件が書かれている求人は、求人ページの「在宅の条件」や注意書きに書いています。</p>
  <p>アルバイト・インターン・業務委託などの契約の形は、募集ページで確かめられたものを求人に表示しています。業務委託や成果報酬の求人は、時給の保証がないことがあります。</p>

  <h2>応募について</h2>
  <p>応募と選考は、各企業の募集ページで行います。zaitoは応募を受け付けたり、取り次いだりしません。募集内容は変わることがあるため、応募する前に元の募集ページも確認してください。</p>

  <h2>掲載内容の修正・削除</h2>
  <p>掲載している企業の方で、内容の修正や掲載の取りやめをご希望の場合は、<a href="mailto:info@zaito-work.com">info@zaito-work.com</a> までご連絡ください。確認のうえ、すぐに対応します。</p>
