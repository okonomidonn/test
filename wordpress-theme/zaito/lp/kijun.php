    'zaitoは、初日・研修・会議を含めて出社を求めない求人だけを載せています。載せる求人と載せない求人、確認のしかた、確認し直す頻度をまとめました。',
    $zaito_canon,
    array(
        '@context'        => 'https://schema.org',
        '@type'           => 'BreadcrumbList',
        'itemListElement' => array(
            array( '@type' => 'ListItem', 'position' => 1, 'name' => 'zaito', 'item' => home_url( '/' ) ),
            array( '@type' => 'ListItem', 'position' => 2, 'name' => '掲載基準', 'item' => $zaito_canon ),
        ),
    )
